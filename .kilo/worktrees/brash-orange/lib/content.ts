export function getPageContent(slug: string[]): PageContent | null {
  const path = slug.join("/").replace(/\/$/, "")

  // Work detail page: /works/<slug>
  if (slug[0] === "works" && slug.length === 2) {
    const work = works.find((w) => w.href.replace(/\/$/, "") === "/" + path)
    if (work) {
      return {
        title: work.title,
        eyebrow: "Выполненная работа",
        lead: `${work.material}, толщина ${work.thickness}, диаметр отверстия ${work.diameter}. Объект: ${work.location}.`,
        image: work.image,
        imageAlt: work.title,
        intro: [
          `На объекте «${work.location}» выполнено отверстие диаметром ${work.diameter} в конструкции из материала «${work.material}» толщиной ${work.thickness}. Работа выполнена безударным алмазным бурением с ровной кромкой без сколов.`,
          `Коронка подобрана точно под задачу, установка закреплена на основании для соблюдения направления и соосности. Для охлаждения использовалась дозированная подача воды, шлам собирался в рабочей зоне, поэтому помещение осталось чистым.`,
          `Похожую задачу можно рассчитать заранее — пришлите фото места, материал, толщину стены и нужный диаметр.`,
        ],
        features: [
          { title: "Материал", text: work.material },
          { title: "Толщина", text: work.thickness },
          { title: "Диаметр", text: work.diameter },
        ],
        sections: ["works", "process", "faq"],
      }
    }
  }

  // Location page: single segment matching a known location
  if (slug.length === 1) {
    const location = locations.find((l) => locationSlug(l) === slug[0])
    if (location) return locationContent(location)
  }

  return serviceContent[path] ?? staticContent[path] ?? null
}

export function pageTitle(slug: string[]): string | null {
  return getPageContent(slug)?.title ?? null
}
